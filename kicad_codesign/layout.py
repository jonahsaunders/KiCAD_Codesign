"""Desktop layout and native navigation, independent of provider requests."""
import wx
import wx.lib.scrolledpanel
from .ui import Card, Preview, StatusPanel, WrappedText, button, font, space, text


def build_interface(frame):
    root = wx.Panel(frame, style=wx.TAB_TRAVERSAL)
    root.SetBackgroundColour(frame.theme.background)
    frame.root = root
    outer = wx.BoxSizer(wx.VERTICAL)
    heading = wx.BoxSizer(wx.HORIZONTAL)
    identity = wx.BoxSizer(wx.VERTICAL)
    identity.Add(text(root, "KiCAD Codesign", size=20, bold=True))
    identity.Add(text(root, "An assistant beside your design", size=10, secondary=True), 0, wx.TOP, space(frame, 4))
    heading.Add(identity, 1, wx.ALIGN_CENTER_VERTICAL)
    frame.connect = button(root, "Connection…", frame.configure, tooltip="Choose a provider and model · Ctrl+,")
    heading.Add(frame.connect, 0, wx.ALIGN_CENTER_VERTICAL | wx.LEFT, space(frame, 10))
    outer.Add(heading, 0, wx.EXPAND | wx.ALL, space(frame, 20))
    frame.provider_label = text(root, "OpenAI · Add your API key in Connection", size=10, secondary=True)
    frame.provider_label.SetWindowStyleFlag(wx.ST_ELLIPSIZE_END)
    outer.Add(frame.provider_label, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.BOTTOM, space(frame, 20))
    frame.notebook = wx.Notebook(root)
    frame.notebook.SetFont(font(10))
    frame.design = wx.lib.scrolledpanel.ScrolledPanel(frame.notebook, style=wx.TAB_TRAVERSAL)
    frame.design.SetBackgroundColour(frame.theme.background)
    frame.notebook.AddPage(frame.design, "Design")
    design_sizer = wx.BoxSizer(wx.VERTICAL)

    editor_card = Card(frame.design)
    row = wx.BoxSizer(wx.HORIZONTAL)
    row.Add(text(editor_card, "Editor", size=12, bold=True), 1, wx.ALIGN_CENTER_VERTICAL)
    frame.refresh_button = button(editor_card, "Refresh", frame.refresh_editors,
                                  tooltip="Find open layout, schematic, and footprint editors")
    row.Add(frame.refresh_button)
    editor_card.body.Add(row, 0, wx.EXPAND | wx.BOTTOM, space(frame, 8))
    frame.choice = wx.Choice(editor_card)
    frame.choice.SetName("KiCad editor")
    frame.choice.SetFont(font(10))
    frame.choice.SetMinSize((1, space(frame, 32)))
    frame.choice.Bind(wx.EVT_CHOICE, frame.selected)
    editor_card.body.Add(frame.choice, 0, wx.EXPAND | wx.BOTTOM, space(frame, 10))
    row = wx.BoxSizer(wx.HORIZONTAL)
    frame.circle_button = button(editor_card, "Circle region", frame.circle,
                                  tooltip="Draw over the selected editor · Ctrl+Shift+Space")
    frame.arrange_button = button(editor_card, "Arrange windows", frame.arrange,
                                   tooltip="Place the editor and assistant beside each other")
    row.Add(frame.circle_button, 1, wx.RIGHT, space(frame, 8))
    row.Add(frame.arrange_button, 1)
    editor_card.body.Add(row, 0, wx.EXPAND)
    design_sizer.Add(editor_card, 0, wx.EXPAND | wx.ALL, space(frame, 12))

    selection_card = Card(frame.design)
    row = wx.BoxSizer(wx.HORIZONTAL)
    row.Add(text(selection_card, "Selection", size=12, bold=True), 1, wx.ALIGN_CENTER_VERTICAL)
    frame.selection_label = text(selection_card, "No region yet", size=10, secondary=True)
    row.Add(frame.selection_label, 0, wx.ALIGN_CENTER_VERTICAL)
    selection_card.body.Add(row, 0, wx.EXPAND | wx.BOTTOM, space(frame, 12))
    frame.preview = Preview(selection_card)
    selection_card.body.Add(frame.preview, 0, wx.EXPAND)
    design_sizer.Add(selection_card, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.BOTTOM, space(frame, 12))

    request_card = Card(frame.design)
    request_card.body.Add(text(request_card, "What would you like to change?", size=12, bold=True), 0, wx.BOTTOM, space(frame, 10))
    frame.prompt = wx.TextCtrl(request_card, style=wx.TE_MULTILINE)
    frame.prompt.SetFont(font(11))
    frame.prompt.SetName("Describe the design change")
    frame.prompt.SetMinSize((1, space(frame, 88)))
    frame.prompt.SetHint("Set the circled resistor to 10k. Keep its position.")
    frame.prompt.Bind(wx.EVT_TEXT, lambda event: frame.controls())
    request_card.body.Add(frame.prompt, 0, wx.EXPAND | wx.BOTTOM, space(frame, 12))
    frame.auto = wx.CheckBox(request_card, label="Apply actions automatically")
    frame.auto.SetFont(font(10))
    frame.auto.SetName("Apply actions automatically, up to 40 actions")
    frame.auto.SetToolTip("Off by default. When on, each action waits briefly before it is applied.")
    frame.auto.Bind(wx.EVT_CHECKBOX, frame.automatic_changed)
    request_card.body.Add(frame.auto, 0, wx.BOTTOM, space(frame, 7))
    request_card.body.Add(WrappedText(request_card, "You review each action by default. You can stop at any time.", secondary=True), 0, wx.EXPAND)
    design_sizer.Add(request_card, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.BOTTOM, space(frame, 12))
    frame.design.SetSizer(design_sizer)
    frame.design.SetupScrolling(scroll_x=False)

    activity = wx.Panel(frame.notebook, style=wx.TAB_TRAVERSAL)
    activity.SetBackgroundColour(frame.theme.surface)
    activity_sizer = wx.BoxSizer(wx.VERTICAL)
    activity_sizer.Add(text(activity, "Activity", size=14, bold=True), 0, wx.ALL, space(frame, 16))
    frame.log = wx.TextCtrl(activity, style=wx.TE_MULTILINE | wx.TE_READONLY | wx.TE_RICH2 | wx.BORDER_NONE)
    frame.log.SetFont(font(10))
    frame.log.SetBackgroundColour(frame.theme.surface)
    frame.log.SetForegroundColour(frame.theme.text)
    frame.log.SetName("Assistant activity and action history")
    activity_sizer.Add(frame.log, 1, wx.EXPAND | wx.LEFT | wx.RIGHT, space(frame, 16))
    frame.history_button = button(activity, "Open history folder", frame.open_history)
    activity_sizer.Add(frame.history_button, 0, wx.ALL, space(frame, 16))
    activity.SetSizer(activity_sizer)
    frame.notebook.AddPage(activity, "Activity")
    outer.Add(frame.notebook, 1, wx.EXPAND | wx.LEFT | wx.RIGHT, space(frame, 8))

    # The footer does not scroll: Stop and action review stay visible.
    footer = Card(root)
    frame.action_panel = wx.Panel(footer)
    frame.action_panel.SetBackgroundColour(frame.theme.tint)
    action_body = wx.BoxSizer(wx.VERTICAL)
    frame.action_title = WrappedText(frame.action_panel, "Next action", size=11)
    frame.action_title.SetFont(font(11, True))
    frame.action_description = WrappedText(frame.action_panel, "")
    action_body.Add(frame.action_title, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.TOP, space(frame, 12))
    action_body.Add(frame.action_description, 0, wx.EXPAND | wx.ALL, space(frame, 12))
    frame.action_panel.SetSizer(action_body)
    footer.body.Add(frame.action_panel, 0, wx.EXPAND | wx.BOTTOM, space(frame, 12))
    frame.action_panel.Hide()
    frame.state = StatusPanel(footer)
    footer.body.Add(frame.state, 0, wx.EXPAND | wx.BOTTOM, space(frame, 14))
    row = wx.BoxSizer(wx.HORIZONTAL)
    frame.undo_button = button(footer, "Undo", frame.undo, tooltip="Undo one edit in KiCad")
    frame.stop_button = button(footer, "Stop", frame.stop, tooltip="Stop · Ctrl+Shift+F12 or hold Esc")
    frame.ask_button = button(footer, "Ask assistant", frame.start, primary=True, tooltip="Start your request · Ctrl+Enter")
    frame.step_button = button(footer, "Apply action", frame.apply_pending, primary=True)
    row.Add(frame.undo_button)
    row.AddStretchSpacer()
    row.Add(frame.stop_button, 0, wx.RIGHT, space(frame, 8))
    row.Add(frame.ask_button)
    row.Add(frame.step_button)
    footer.body.Add(row, 0, wx.EXPAND)
    footer.body.Add(WrappedText(footer, "Ask sends the selected editor view to your provider.", secondary=True, size=9),
                    0, wx.EXPAND | wx.TOP, space(frame, 10))
    outer.Add(footer, 0, wx.EXPAND | wx.ALL, space(frame, 8))
    root.SetSizer(outer)
    frame_sizer = wx.BoxSizer(wx.VERTICAL)
    frame_sizer.Add(root, 1, wx.EXPAND)
    frame.SetSizer(frame_sizer)


def build_menu(frame):
    bar = wx.MenuBar()
    file_menu, edit_menu, help_menu = wx.Menu(), wx.Menu(), wx.Menu()
    file_menu.Append(wx.ID_OPEN, "Open &practice design…")
    file_menu.AppendSeparator()
    file_menu.Append(wx.ID_EXIT, "E&xit")
    frame.undo_menu = edit_menu.Append(wx.ID_UNDO, "&Undo in KiCad")
    frame.connection_menu = edit_menu.Append(wx.ID_PREFERENCES, "&Connection…\tCtrl+,")
    frame.history_id, frame.shortcuts_id = wx.NewIdRef(), wx.NewIdRef()
    help_menu.Append(frame.shortcuts_id, "&Keyboard shortcuts")
    help_menu.Append(frame.history_id, "Open session &history")
    for menu, name in ((file_menu, "&File"), (edit_menu, "&Edit"), (help_menu, "&Help")):
        bar.Append(menu, name)
    frame.SetMenuBar(bar)
    for identifier, handler in ((wx.ID_OPEN, frame.open_demo), (wx.ID_EXIT, lambda event: frame.Close()),
                                (wx.ID_UNDO, frame.undo), (wx.ID_PREFERENCES, frame.configure),
                                (frame.history_id, frame.open_history), (frame.shortcuts_id, frame.shortcuts)):
        frame.Bind(wx.EVT_MENU, handler, id=identifier)
